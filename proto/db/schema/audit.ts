import { index, jsonb, pgTable, text, timestamp, uuid } from 'drizzle-orm/pg-core';

// Журнал действий: кто, когда и что изменил.
//
// ЗАЧЕМ. «Кто изменил цену» — первый вопрос при разборе любой претензии. Сейчас на
// него ответить нечем: `line.updated_at` говорит, что строку трогали, но не говорит
// КТО и ЧТО было до этого. Пункт 20 БТ закрыт наполовину: «кто создал» мы знаем
// (`author_id`), «кто ещё трогал» — нет.
//
// ПОЧЕМУ ЛОГИН И РОЛЬ ЛЕЖАТ ЗДЕСЬ ЖЕ, А НЕ ТОЛЬКО ССЫЛКОЙ. Журнал должен читаться
// после того, как учётную запись переименовали или удалили. Ссылка на пользователя
// этого не даёт: через месяц в записи будет пустой идентификатор, и разбор
// прекратится. Денормализация здесь — не дублирование, а условие читаемости.
//
// ПОЧЕМУ `details`, А НЕ `extra`. `extra` — имя из наследия 1С, и в проекте есть
// проверка «в БД нет ни одного столбца наследия». Первая версия этого файла её
// сломала. Соблазн был записать столбец в исключения — но исключение из правила
// «никаких имён наследия» и есть начало конца этого правила. Переименование стоило
// одной минуты.

export const auditLog = pgTable(
  'audit_log',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    at: timestamp('at', { withTimezone: true }).notNull().defaultNow(),

    /** Кто. Пусто — работа по заголовку `X-Role` (демо и автотесты). */
    userId: uuid('user_id'),
    /** Логин на МОМЕНТ записи. Денормализован осознанно — см. комментарий выше. */
    login: text('login'),
    role: text('role'),

    /** Что меняли: таблица и идентификатор записи. */
    entity: text('entity').notNull(),
    entityId: uuid('entity_id').notNull(),

    /**
     * Вид действия: `create`, `update`, `delete`, `transition`.
     *
     * `transition` отдельно от `update`: смена состояния — не правка поля, и искать
     * её в одном списке с ценами неудобно.
     */
    action: text('action').notNull(),

    /** Какое поле, если меняли одно. Пусто — меняли запись целиком. */
    field: text('field'),
    /** Было и стало. Текстом: человек читает, а не сравнивает типы. */
    oldValue: text('old_value'),
    newValue: text('new_value'),
    /** Пояснение: причина отказа, номер документа, куда перевели. */
    comment: text('comment'),

    /** Идентификатор запроса — по нему разбор связывается с логами сервера. */
    traceId: uuid('trace_id'),
    /** Дополнительные данные: исходные типы, состав строки при создании. */
    details: jsonb('details').notNull().default({}),
  },
  (t) => [
    // Основной запрос — «история ЭТОЙ записи», поэтому составной индекс.
    index('audit_entity_idx').on(t.entity, t.entityId, t.at),
    index('audit_user_idx').on(t.userId, t.at),
    index('audit_at_idx').on(t.at),
  ],
);
