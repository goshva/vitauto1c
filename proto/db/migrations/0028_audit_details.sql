-- Переименование столбца журнала: extra → details.
--
-- `extra` — имя из наследия 1С, а в проекте есть проверка «в БД нет ни одного столбца
-- наследия». Первая версия журнала её сломала.
--
-- СОБЛАЗН БЫЛ ЗАПИСАТЬ СТОЛБЕЦ В ИСКЛЮЧЕНИЯ — но исключение из правила «никаких
-- имён наследия» и есть начало конца этого правила: через полгода исключений стало бы
-- пять, и проверка перестала бы что-либо значить. Переименование стоило минуты.
--
-- Отдельной миграцией, а не правкой 0027: миграция 0027 уже применена, и дописать в
-- неё з��ачило бы получить разное состояние у того, кто применил раньше, и у того, кто
-- применит позже.

ALTER TABLE audit_log RENAME COLUMN extra TO details;
