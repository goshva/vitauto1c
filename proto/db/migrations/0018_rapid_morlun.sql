 where zone_id = '99999999-9999-9999-9999-999999999905';
update receipt set zone_id = '99999999-9999-9999-9999-999999999904'
 where zone_id = '99999999-9999-9999-9999-999999999905';

delete from warehouse_zone where id = '99999999-9999-9999-9999-999999999905';

-- ── Названия и признак «предопределённая» ───────────────────────────────────────────
-- Названия и назначения — ДОСЛОВНО из утверждённой схемы: оператор видит в списке
-- то же, что в ТЗ, и сверка не требует переводчика.
update warehouse_zone set predefined = false;

