-- Шесть предопределённых зон склада по утверждённой схеме (ФТ v2 п. 7).
--
-- Источник схемы — НЕ догадка: `db/migrations/0014_warehouse_zones.sql` (legacy) и
-- вкладка «Складские зоны» в `process.html`. Утверждены шесть:
--   Z1  Зона приёмки            — приёмка по УПД, факт прихода
--   Z3  Малый склад             — мелкие детали
--   Z4  Большой склад           — крупногабарит, жидкости
--   Z5  Неопознанные и возвраты — брак, возврат, неопознание
--   Z7  Ремонтная зона          — заказ-наряды, механик
--   Z9  Зона укомплектованных   — готово к отгрузке
--
-- ЧТО ИСПРАВЛЯЕТСЯ
--
-- 1. «Неопознанные» и «Возвраты» были РАЗНЫМИ зонами (`UNK`, `RET`). По схеме это
--    ОДНА зона Z5: и брак, и возврат, и неопознанное лежат вместе, потому что
--    разбирает их один человек в одном месте. Сливаем в одну.
--
-- 2. Появляется признак `predefined`. До него «шесть предопределённых» нельзя было
--    ни проверить, ни показать: в справочнике лежало двенадцать зон, и какая из них
--    утверждённая, а какая служебная — не знал никто, кроме автора сида.
--
-- Служебные зоны (резерв/комплектация, отгрузка, опознание админом, списание по ЗН)
-- остаются и помечаются `predefined = false`: они описаны в модели процесса (Z6, Z8,
-- Z10, Z12) и нужны работающим операциям, но в утверждённую шестёрку не входят.


-- ── Слияние Z5 ──────────────────────────────────────────────────────────────────────
-- Переносим всё, что ссылалось на «Возвраты», в «Неопознанные» — до удаления зоны.
