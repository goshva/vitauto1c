import { seedRefs, seedExtra } from './seed.ts';
import { planMonth } from '../src/domain/econ-plan.ts';
import type { MonthParams, MonthPlan } from '../src/domain/econ.ts';

// СИД МЕСЯЦА: справочники, чистое состояние и входные значения.
//
// ПОЧЕМУ СИД НЕ СОЗДАЁТ ПРОВОДКИ. Месяц должен быть получен ДЕЙСТВИЯМИ сотрудников
// (`scripts/econ-run.ts`), а не вставкой строк: если бы сид сразу клал готовые заказы
// с ценами и отгрузками, «предварительный расчёт» и «факт» сверялись бы с одним и тем
// же источником, и сверка не проверяла бы ничего.
//
// Сид отвечает за три вещи: справочники (номенклатура, предложения, сотрудники,
// машины), чистое состояние транзакций и ВХОДНЫЕ значения месяца — количества,
// закупочные цены, множители, нормо-часы. Цены продажи в них не входят: их считает
// сервер, когда менеджер ставит множитель.
export async function prepareMonth(params: MonthParams): Promise<MonthPlan> {
  await seedRefs();
  await seedExtra.clear();
  return planMonth(params);
}
