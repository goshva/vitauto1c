// Разбор чисел из вставленного текста (ФТ v2 п. 8).
//
// Отдельно от шаблона, и не только по размеру файла. Правила чисел живут дольше
// колонок: состав заявки меняется, а «1 234,56» из Excel останется тем же — и
// ошибиться в нём по-прежнему легче всего.
//
// Про «порчу чисел» стоит сказать отдельно, потому что это и есть суть требования.
// Excel в русской локали печатает дробную часть через запятую, а разряды разделяет
// ПРОБЕЛОМ (иногда неразрывным): «1 234,56». Наивный разбор даёт 1 и мусор — или
// 123456. Ошибка ТИХАЯ: строка создастся, количество будет неверным, и заметят это
// на складе.

/**
 * Разбор числа из ячейки.
 *
 * Правила, и каждое взято из живой накладной, а не из головы:
 *   — пробелы (обычный, неразрывный, узкий) внутри числа ВЫБРАСЫВАЮТСЯ: ими Excel
 *     разделяет разряды;
 *   — запятая и точка равнозначны как десятичный разделитель;
 *   — если после разделителя РОВНО три цифры и других разделителей нет, это разряды
 *     («1,234» → 1234), иначе дробь («1,23» → 1.23). Неоднозначность реальна, поэтому
 *     правило названо явно, а не спрятано.
 */
export function parseQuantity(raw: string): string | null {  const s = raw.replace(/[\s\u00a0\u202f]/g, '').trim();
  if (s === '') return null;

  const seps = [...s].filter((ch) => ch === ',' || ch === '.');
  let normalized: string;

  if (seps.length > 1) {
    // Несколько разделителей: последний — десятичный, остальные разряды.
    const at = Math.max(s.lastIndexOf(','), s.lastIndexOf('.'));
    normalized = s.slice(0, at).replace(/[.,]/g, '') + '.' + s.slice(at + 1);
  } else if (seps.length === 1) {
    const at = s.search(/[.,]/);
    const tail = s.slice(at + 1);
    // «1,234» — разряды; «1,23» и «1,2345» — дробь.
    normalized = tail.length === 3
      ? s.slice(0, at) + tail
      : s.slice(0, at) + '.' + tail;
  } else {
    normalized = s;
  }

  const n = Number(normalized);
  return Number.isFinite(n) && n > 0 ? String(n) : null;
}

/**
 * Срочность: «да», «+», «1», «true» — срочно. Пусто и «нет» — нет.
 *
 * Список шире одного «да» намеренно: в реестрах пишут по-разному, а столбец этот
 * заполняют руками и второпях.
 */
export const parseUrgent = (raw: string): boolean =>
  ['да', 'yes', '+', '1', 'true', 'истина'].includes(raw.trim().toLowerCase());
