// Сопоставление позиций клиента со справочником (п. 2).
//
// ВЫБОР СЧЁТЧИКА СДЕЛАН ПО ЗАМЕРУ НА ЖИВЫХ ДАННЫХ, а не по документации:
//
//   · `pg_trgm` отпадает — в этой базе локаль `C` с UTF8, и на ОДИНАКОВЫХ русских
//     строках он даёт 0. То есть точного совпадения не находит вовсе;
//   · Левенштейн отпадает в одиночку — «Катушка зажигания» против «Свеча зажигания»
//     он оценивает в 0.65, что ВЫШЕ худшего настоящего совпадения (0.60). По нему
//     разные детали похожи сильнее, чем та же деталь с уточнением;
//   · Жаккар по словам теряет уточнения: «Свеча зажигания иридиевая» против «Свеча
//     зажигания» — 0.67, и при пороге 0.8 точное совпадение с уточнением не подставится.
//
// ОСТАЁТСЯ ВЕС ГЛАВНОГО СЛОВА. Модификаторы («передний», «задний», «левый», «в сборе»)
// стоят у половины позиций и совпадают у РАЗНЫХ деталей. Главное слово называет саму
// деталь — оно и весит больше. Разделение ступеней на живых данных: зазор +0.60 против
// +0.00 у Жаккара и −0.05 у Левенштейна.

/** Пороги полос. Вынесены наружу: по ним принимают решение, и они должны быть видны. */
export const MATCH_BANDS = {
  /** Столько и выше — подставляем сразу, без вопроса. */
  auto: 0.8,
  /** Отсюда и до `auto` — показываем список, выбирает оператор. */
  choose: 0.45,
} as const;

type MatchBand = 'auto' | 'choose' | 'none';

interface Candidate {
  id: string;
  name: string;
  /** Артикул для показа рядом с названием. */
  article?: string | null;
}

export interface Suggestion extends Candidate {
  score: number;
  band: MatchBand;
  /** Какие слова совпали — чтобы оператор видел, ПОЧЕМУ это предложено. */
  common: string[];
  /** Совпало ли главное слово. */
  headMatch: boolean;
}

/**
 * Слова, которые есть почти у всех и о детали не говорят.
 *
 * «Передний» и «задний» — самые опасные: они совпадают у РАЗНЫХ деталей, и именно из-за
 * них дешёвый счётчик зовёт «Катушку зажигания» похожей на «Свечу зажигания».
 */
const STOP = new Set([
  'и', 'в', 'с', 'на', 'для', 'по', 'от', 'до', 'из',
  'шт', 'штука', 'комплект', 'набор', 'сборе', 'сбор', 'аналог', 'образец',
  'передний', 'передняя', 'переднее', 'передние', 'перед',
  'задний', 'задняя', 'заднее', 'задние', 'зад',
  'левый', 'левая', 'левое', 'левые',
  'правый', 'правая', 'правое', 'правые',
  'верхний', 'нижний', 'внутренний', 'наружный',
]);

/** Приведение к сравнимому виду: регистр, ё, знаки, лишние пробелы. */
const normalize = (s: string): string => s.toLowerCase().replace(/ё/g, 'е')
  .replace(/[^\p{L}\p{N}\s]/gu, ' ').replace(/\s+/g, ' ').trim();

/** Значимые слова: без стоп-слов и без пустых. */
/** Значимые слова: без стоп-слов и без пустых. */
function significantWords(s: string): string[] {
  return normalize(s).split(' ').filter((w) => w !== '' && !STOP.has(w));
}

/**
 * Слова для СРАВНЕНИЯ: значимые минус слова брендов.
 *
 * Бренд убирается с ОБЕИХ сторон, и на то две причины.
 *
 * Во-первых, он не называет деталь: клиент пишет «Bosch Фильтр масляный», и главным
 * словом должен остаться «фильтр» — иначе позиция сойдётся с любой другого бренда.
 *
 * Во-вторых, в справочнике бренд В НАЗВАНИИ НЕ ХРАНИТСЯ — он отдельное поле. Оставь
 * мы его в словах клиента, он считался бы лишним уточнением и СНИЖАЛ уверенность.
 * Проверено тестом: «Bosch Фильтр масляный» давало 0.72 вместо 1.00 — то есть бренд,
 * написанный клиентом, работал ПРОТИВ совпадения.
 */
function comparableWords(s: string, brands: string[]): string[] {
  if (brands.length === 0) return significantWords(s);
  const brandWords = new Set(brands.flatMap((b) => significantWords(b)));
  return significantWords(s).filter((w) => !brandWords.has(w));
}

/** Главное слово — первое слово для сравнения. Бренды уже убраны. */
function headWord(s: string, brands: string[] = []): string | null {
  return comparableWords(s, brands)[0] ?? null;
}

/** Совпадение главных слов: 1 — то же слово, 0.6 — одно начало другого, 0 — разное. */
function headMatch(a: string | null, b: string | null): number {
  if (!a || !b) return 0;
  if (a === b) return 1;
  // «фильтр» и «фильтры», «масло» и «масляный» — одно начинается другим. Ровно это
  // спасает на опечатке в справочнике: «тормоaasзные» начинается как «тормозные»? нет —
  // и потому здесь именно 0.6, а не 1: слово похоже, но не совпало.
  if (a.startsWith(b) || b.startsWith(a)) return 0.6;
  // Общий корень в 4 буквы: «колодк»/«колодки», «тормозн»/«тормоaasзн».
  const prefix = (x: string, y: string): number => {
    let i = 0;
    while (i < x.length && i < y.length && x[i] === y[i]) i++;
    return i;
  };
  return prefix(a, b) >= 4 ? 0.4 : 0;
}

/** Доля общих значимых слов. */
function jaccard(a: string[], b: string[]): number {
  const A = new Set(a); const B = new Set(b);
  if (A.size === 0 || B.size === 0) return 0;
  const common = [...A].filter((w) => B.has(w)).length;
  return common / (A.size + B.size - common);
}

/**
 * Оценка похожести: общие слова, вес главного и ПОКРЫТИЕ слов клиента.
 *
 * 0.4 и 0.6 подобраны не на глаз: при таком весе ступени на живых данных расходятся с
 * зазором, а «Катушка зажигания» против «Свечи зажигания» получает 0.13 — то есть
 * правильно сомневается вместо уверенной ошибки.
 *
 * ПОКРЫТИЕ ДОБАВЛЕНО ПО НАЙДЕННОМУ ИЗЪЯНУ, и это самая тонкая часть правила. Смотри
 * две пары, которые сначала считались одинаково уверенными:
 *
 *   «Масло моторное 5W-30»       → «Масло моторное 5W-30 (5л)»   — ПОДСТАВЛЯТЬ МОЖНО
 *   «Свеча зажигания иридиевая»  → «Свеча зажигания»             — ПОДСТАВЛЯТЬ НЕЛЬЗЯ
 *
 * Разница в том, ГДЕ лишнее слово. В первом случае уточнение есть в справочнике, а
 * клиент его опустил: он написал меньше, и позиция та же. Во втором клиент написал
 * БОЛЬШЕ — «иридиевая» это свойство детали, и в справочнике её нет: значит там ДРУГАЯ,
 * более простая деталь. Подставить её значит выдать не то.
 *
 * Поэтому от оценки берётся доля слов КЛИЕНТА, найденных в справочнике: не покрыл —
 * значит сказал лишнее, и уверенность снижается.
 */
export function scoreOf(written: string, candidate: string, brands: string[] = []): {
  score: number;
  common: string[];
  headMatch: boolean;
} {
  // Слова без брендов: они есть у половины позиций и о самой детали не говорят.
  const w = comparableWords(written, brands);
  const c = comparableWords(candidate, brands);
  const common = w.filter((x) => c.includes(x));

  const wh = headWord(written, brands);
  const ch = headWord(candidate, brands);
  const hm = headMatch(wh, ch);

  const base = jaccard(w, c) * 0.4 + hm * 0.6;
  // Покрытие слов клиента: 1 — все его слова есть в справочнике, 0.5 — половина.
  const coverage = w.length === 0 ? 0 : common.length / w.length;
  // Вдвое ослабляем только при полном непокрытии: 0.5 при coverage 0, 1.0 при 1.
  const factor = 0.5 + 0.5 * coverage;

  return {
    score: base * factor,
    common,
    headMatch: hm >= 0.6,
  };
}

/** Полоса по оценке. */
export function bandOf(score: number): MatchBand {
  if (score >= MATCH_BANDS.auto) return 'auto';
  if (score >= MATCH_BANDS.choose) return 'choose';
  return 'none';
}

/**
 * Предложения по написанию клиента: от лучшего к худшему.
 *
 * Возвращаются ВСЕ полосы, включая `none`: вызывающий решает, что показать. Отдавать
 * только «хорошие» значило бы скрыть, что ничего не найдено, — а это главный ответ.
 */
export function suggest(
  written: string,
  candidates: Candidate[],
  options: { brands?: string[]; limit?: number } = {},
): Suggestion[] {
  const brands = options.brands ?? [];
  const limit = options.limit ?? 5;

  return candidates
    .map((c) => {
      const s = scoreOf(written, c.name, brands);
      return { ...c, score: s.score, band: bandOf(s.score), common: s.common, headMatch: s.headMatch };
    })
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
}
