// Права ролей (Q7): пять ролей и закрытый список действий.
//
// Роль — это ПРАВО, а не человек: `mechanic` может выполнять работы, а подпись
// в акте ставит конкретный сотрудник (`employee.can_sign`). Здесь только права.
//
// ПОЧЕМУ действия, а не «роль видит экран»: одна и та же роль открывает список
// и НЕ может закрыть наряд. Проверять по «роль X не ходит на адрес Y» значило бы
// запрещать экран целиком, а нужно запрещать ОПЕРАЦИЮ.

export type Role = 'admin' | 'municipality' | 'manager' | 'mechanic' | 'storekeeper';

export type Action =
  | 'dashboard.view'
  | 'request.create'
  | 'request.view'
  | 'work.execute'
  | 'stock.issue'
  | 'fleet.edit'
  | 'invoice.manage'
  /** Удаление документов и строк (ФТ v2 п. 15). */
  | 'data.delete'
  /**
   * Новая закупка (ФТ v2 п. 16). Решение заказчика (14.11.2026): «право вшито в
   * роль менеджера и администратора». Кладовщик закупку не делает — он принимает
   * то, что пришло, и цены закупки ему закрыты (п. 5).
   */
  | 'purchase.create'
  /**
   * Возврат: клиента и поставщику (БТ п. 18).
   *
   * БТ: «Заявку на возврат поставщику может оформить **как менеджер, так и
   * кладовщик**». Поэтому право отдельное: `stock.issue` есть только у кладовщика,
   * а возврат оформляют оба.
   */
  | 'return.create'
  /**
   * Чтение журнала действий.
   *
   * Пишут все, кто что-то меняет, — иначе журнал неполон. Читают не все: журнал
   * показывает себестоимость, цены и историю правок, то есть закрытые данные
   * (ФТ v2 п. 5). Поэтому право отдельное и только у администратора.
   */
  | 'audit.read'
  /**
   * Регламентные задания: смотреть расписание и запускать вручную.
   *
   * Запускать вручную может только администратор. Не потому, что задание опасное
   * само по себе, а потому, что ручной пуск сбивает расписание: снятая вручную копия
   * сдвигает срок следующей.
   */
  | 'job.run'
  /**
   * Отчёты с себестоимостью и прибылью.
   *
   * ПОЧЕМУ ОТДЕЛЬНОЕ ПРАВО, А НЕ ЗАКРЫТИЕ КОЛОНОК. В списке строк себестоимость можно
   * просто не показывать — там есть другие колонки, и работа не останавливается. В
   * отчёте так нельзя: прятать колонку бесполезно, потому что ИТОГ по ней всё равно
   * покажет себестоимость, а вместе с ней и прибыль.
   *
   * Поэтому отчёт с себестоимостью не «показывается частично», а НЕ ОТКРЫВАЕТСЯ ролям,
   * которым себестоимость закрыта (ФТ v2 п. 5: кладовщик и механик — без цен закупки
   * и себестоимости).
   */
  | 'report.cost'
  /**
   * Назначение строке процесса (сценария модели).
   *
   * Без этого действия строка, созданная через API, в процессе не числится, и
   * пошаговое движение `/lines/step` для неё недоступно (`docs/fix-plan.md` §4).
   * Право узкое: назначение решает, по какому сценарию строка пойдёт дальше.
   */
  | 'process.assign'
  /**
   * История заказ-наряда.
   *
   * Решение заказчика (20.11.2026): историю наряда видит АДМИНИСТРАТОР И МЕХАНИК, но
   * БЕЗ СЕБЕСТОИМОСТИ. Поэтому это не `audit.read` (тот открыт только администратору
   * и показывает цены): отдельное право и отдельный адрес, где закупочные цены
   * вырезаны из ответа.
   */
  | 'work_order.history';

/**
 * Кто что может.
 *
 * `admin` есть везде: условие заказчика — «на старте один админ делает всё за всех».
 * Это не ослабление модели, а её текущее состояние: роли вводятся постепенно,
 * и админ остаётся тем, кто закрывает пробелы.
 */
const ALLOWED: Record<Action, Role[]> = {
  'dashboard.view': ['admin'],
  'request.create': ['municipality', 'manager', 'admin'],
  'request.view': ['municipality', 'manager', 'mechanic', 'storekeeper', 'admin'],
  // Работу выполняет механик. Менеджер и заказчик этого не делают — иначе
  // «выработка механиков» перестаёт что-либо значить.
  'work.execute': ['mechanic', 'admin'],
  'stock.issue': ['storekeeper', 'admin'],
  'fleet.edit': ['manager', 'admin'],
  'invoice.manage': ['manager', 'admin'],
  // Удаление — администратор И МЕНЕДЖЕР (решение заказчика, 14.11.2026).
  //
  // ФТ v2 п. 15 говорит «право „Удаление“ снято для всех профилей КРОМЕ
  // администратора», и первая версия закрыла его до одного админа. Заказчик
  // уточнил: удалять может и менеджер. Кладовщик, механик и муниципалитет — нет.
  //
  // Право намеренно УЖЕ права на правку: менеджер и так правит документы, а
  // удаление — отдельное решение, и оно осталось узким.
  'data.delete': ['admin', 'manager'],
  // Закупка — менеджер и администратор (решение заказчика 14.11.2026).
  'purchase.create': ['manager', 'admin'],
  // Возврат — менеджер И кладовщик: так требует БТ п. 18 дословно.
  'return.create': ['manager', 'storekeeper', 'admin'],
  // Журнал действий — только администратор: там себестоимость и история цен.
  'audit.read': ['admin'],
  // Расписание и ручной пуск — администратор: ручной пуск сдвигает срок следующего.
  'job.run': ['admin'],
  // Отчёты с себестоимостью — те же роли, что видят себестоимость в строках:
  // менеджер и администратор. Кладовщику и механику закрыто (ФТ v2 п. 5).
  'report.cost': ['manager', 'admin'],
  // Назначение процесса — менеджер и администратор: он же ведёт заявку и выбирает
  // ветвь сценария (со склада или под заказ).
  'process.assign': ['manager', 'admin'],
  // История наряда — администратор и механик, без себестоимости (см. описание действия).
  // Менеджеру здесь отказано намеренно: цены он видит в других местах, а история наряда
  // задумана как рабочая летопись ремонта, а не как выгрузка закупок.
  'work_order.history': ['mechanic', 'admin'],
};

const ALL_ROLES: Role[] = ['admin', 'municipality', 'manager', 'mechanic', 'storekeeper'];

/** Роль существует? Сообщение об ошибке перечисляет допустимые — как везде. */
export function checkRole(role: string): string | null {
  if (ALL_ROLES.includes(role as Role)) return null;
  return `Роль «${role}» неизвестна. Допустимые: ${ALL_ROLES.join(', ')}.`;
}

export const isAllowed = (role: string, action: Action): boolean =>
  ALLOWED[action].includes(role as Role);

/**
 * Проверка права.
 *
 * Возвращается ПРИЧИНА отказа или `null` — так же, как у переходов состояния.
 * Отказ перечисляет, у КОГО есть право: иначе оператор не знает, к кому идти,
 * и запрет превращается в «кнопка не работает».
 */
export function checkAccess(role: string, action: Action): string | null {
  const roleProblem = checkRole(role);
  if (roleProblem) return roleProblem;
  if (isAllowed(role, action)) return null;

  return `Роль «${role}» не может выполнить действие «${action}». Это доступно: ${ALLOWED[action].join(', ')}.`;
}
