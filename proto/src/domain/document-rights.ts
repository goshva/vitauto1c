import type { Context } from 'hono';
import { actorOf } from '../auth.ts';
import { Problem } from '../problem.ts';

// Права ПО АВТОРУ документа (ФТ v2 п. 20).
//
// Отдельно от `auth.ts`, и не только потому, что там упёрлись в предел экспортов.
// Вопросы разные: `auth.ts` отвечает «что можно роли», а здесь — «можно ли трогать
// ЭТОТ документ». Менеджер менеджеру не указ, но чужой документ он не правит.

/**
 * Права ПО АВТОРУ документа (ФТ v2 п. 20).
 *
 * ФТ: «„Изменение“ — только автор документа, „Просмотр“ — по профилю доступа.
 * Администратор — полный доступ». Роль здесь ни при чём: менеджер менеджеру не
 * указ, но чужой документ он не правит.
 *
 * Возвращает причину отказа или `null`.
 */
export function checkAuthor(c: Context, authorId: string | null): Problem | null {
  const { userId, role } = actorOf(c);

  // Администратор — полный доступ: так требует ФТ, и так работает демо
  // «один админ делает всё за всех».
  if (role === 'admin') return null;

  // Документ без автора правит любой, у кого есть право на действие: он его не
  // «перехватывает», а заполняет. Иначе заявка, заведённая загрузкой листа,
  // оказалась бы ничьей и недоступной навсегда.
  if (!authorId) return null;

  // Работа по заголовку (демо и тесты): пользователя нет, и сверять не с чем.
  // Отказывать здесь значило бы сломать демонстрацию, ничего не защитив.
  if (!userId) return null;

  if (userId === authorId) return null;

  return new Problem(403, 'not_author',
    'Изменить документ может только его автор. Посмотреть — можно, изменить — нет.');
}
