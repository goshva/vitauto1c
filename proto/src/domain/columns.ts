// Закрытые КОЛОНКИ: что роль не должна видеть (ФТ v2 п. 5).
//
// Отдельный слой от прав по действию, и намеренно. Право по действию отвечает на
// «может ли кладовщик открыть список строк» — может, это его работа. А видеть в
// этом списке себестоимость он не должен: ФТ v2 п. 5 говорит прямо —
// «Кладовщик — складские документы и колонки движения, БЕЗ ЦЕН ЗАКУПКИ И
// СЕБЕСТОИМОСТИ».
//
// Смешать эти два слоя значило бы запретить кладовщику работать целиком: список
// строк — его основной экран, и закрывать его из-за одной колонки нельзя.
//
// ПОЧЕМУ ЭТО НЕ КОСМЕТИКА. Раньше ограничений по колонкам не было вовсе: экран
// себестоимость не показывал, а API её возвращал — и получить её можно было одной
// строкой в консоли браузера. Проверка вызовом `/lines` под ролью `storekeeper`
// показывала `costPrice` и `costSum` в ответе.

/**
 * Что роль НЕ видит.
 *
 * Оба написания намеренно: в ответе списка поля идут из `line_view` как `camelCase`
 * (`costPrice`), а в правке строки клиент присылает имя колонки — `snake_case`
 * (`cost_price`). Закрой мы одно написание — дверь осталась бы открытой рядом.
 */
const HIDDEN: Record<string, readonly string[]> = {
  storekeeper: ['costPrice', 'costSum', 'cost_price', 'cost_sum', 'total', 'price'],
  mechanic: ['costPrice', 'costSum', 'cost_price', 'cost_sum', 'total', 'price'],
};

/**
 * Цена ПРОДАЖИ не закрыта — и это осознанно.
 *
 * ФТ v2 п. 5 запрещает кладовщику «цены закупки и себестоимость», а не любые цены.
 * Расширять запрет шире написанного нельзя: кладовщик выписывает отгрузочные
 * документы, и цена продажи в них есть. Если заказчик хочет закрыть и её — это
 * отдельное решение, и его надо получить явно.
 */

/** Закрыто ли поле для роли. */
export const isHidden = (role: string, field: string): boolean =>
  (HIDDEN[role] ?? []).includes(field);

/**
 * Убирает закрытые поля из ответа. Поля УДАЛЯЮТСЯ, а не обнуляются: `null`
 * читается как «данных нет», и оператор решил бы, что себестоимость не заполнена,
 * а не что она от него закрыта.
 */
export function hideColumns<T extends Record<string, unknown>>(role: string, rows: T[]): T[] {
  const hidden = HIDDEN[role] ?? [];
  if (hidden.length === 0) return rows;
  return rows.map((row) => {
    const copy = { ...row };
    for (const field of hidden) delete copy[field];
    return copy;
  });
}

/**
 * Причина отказа в правке закрытого поля или `null`.
 *
 * Причина называет РОЛЬ и поле: иначе оператор видит «нельзя» и не понимает,
 * почему у соседа та же кнопка работает.
 */
export function deniedColumn(role: string, field: string): string | null {
  if (!isHidden(role, field)) return null;
  return `Роль «${role}» не может править поле «${field}»: цены закупки и себестоимость ей закрыты. Это доступно: manager, admin.`;
}
