import { z } from 'zod';

// UUID-схема для параметров путей.
//
// Почему НЕ `z.string().uuid()`: в Zod 4 эта проверка строгая по RFC 9562 —
// требует версию 1–8 в третьей группе и вариант 8/9/a/b в четвёртой. Сиды прототипа
// (и данные legacy) используют читаемые шаблоны вида `77777777-7777-7777-7777-…`
// и `b0000000-0000-0000-0000-…`, которые строгая проверка отвергает, хотя Postgres
// тип `uuid` их принимает.
//
// Проверка остаётся: форма UUID и только шестнадцатеричные цифры.
export const uuid = z
  .string()
  .regex(
    /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i,
    'Ожидается UUID вида xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx',
  );

export type Uuid = z.infer<typeof uuid>;
