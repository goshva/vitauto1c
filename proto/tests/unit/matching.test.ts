import { describe, expect, test } from 'bun:test';
import {
  MATCH_BANDS, bandOf, scoreOf, suggest,
} from '../../src/domain/matching.ts';

// Алгоритм похожести — проверяется НА ЖИВЫХ ПАРАХ из legacy-базы.
//
// Отдельно от интеграционных тестов: здесь проверяется СЧЁТЧИК, а не маршруты. Пары
// взяты из настоящего справочника и настоящих написаний — те же строки, по которым
// выбирался алгоритм. Если счётчик перестанет их различать, это будет видно здесь, а не
// на складе.

const BRANDS = ['Витавто', 'Bosch', 'Denso', 'Febi Bilstein', 'Liqui Moly', 'Mann-Filter'];

describe('похожесть · приведение к сравнимому виду — через поведение', () => {
  // Внутренние функции (нормализация, разбор слов, главное слово) больше не
  // экспортируются: проверять устройство вместо поведения — значит ломать тесты
  // при каждой разумной правке внутри.
  test('регистр, ё, знаки и пробелы не мешают совпадению', () => {
    const a = scoreOf('  ФИЛЬТР   МАСЛЯНЫЙ (5л) ', 'фильтр масляный 5л');
    expect(a.score, 'оформление помешало совпадению').toBeGreaterThanOrEqual(MATCH_BANDS.auto);
  });

  test('стоп-слова не мешают: «передний» и «задний» есть у РАЗНЫХ деталей', () => {
    // Если бы они считались значимыми, «Диск тормозной передний» сошёлся бы с
    // «Колодками тормозными передними» — а это разные детали.
    const s = scoreOf('Диск тормозной передний вентилируемый',
      'Колодки тормозные передние', BRANDS);
    expect(s.score, 'модификаторы свели разные детали вместе')
      .toBeLessThan(MATCH_BANDS.choose);
  });

  test('ВЕДУЩИЙ БРЕНД не становится главным словом', () => {
    // Клиент пишет «Bosch Фильтр масляный» — бренд первым. Главным словом должна
    // остаться ДЕТАЛЬ, иначе совпадёт у всех позиций бренда.
    const withBrand = scoreOf('Bosch Фильтр масляный', 'Фильтр масляный', BRANDS);
    const without = scoreOf('Фильтр масляный', 'Фильтр масляный', BRANDS);
    expect(withBrand.score, 'бренд помешал совпадению')
      .toBeGreaterThanOrEqual(MATCH_BANDS.auto);
    expect(without.score).toBeGreaterThanOrEqual(withBrand.score - 0.001);
  });
});
describe('похожесть · СИЛЬНО (≥ 0.80) — можно подставлять', () => {
  const cases: [string, string][] = [
    ['Фильтр масляный', 'Фильтр масляный'],
    ['Фильтр воздушный', 'Фильтр воздушный'],
    ['Фильтр салонный', 'Фильтр салонный'],
    ['Свеча зажигания', 'Свеча зажигания'],
    ['Масло моторное 5W-30', 'Масло моторное 5W-30 (5л)'],
    ['Антифриз G12+', 'Антифриз G12+ (5л)'],
  ];

  for (const [written, catalogue] of cases) {
    test(`«${written}» → «${catalogue}»`, () => {
      const s = scoreOf(written, catalogue, BRANDS);
      expect(s.score, `оценка ${s.score.toFixed(2)} ниже порога подстановки`)
        .toBeGreaterThanOrEqual(MATCH_BANDS.auto);
      expect(s.headMatch, 'главное слово не совпало').toBe(true);
    });
  }
});

describe('похожесть · СРЕДНЕ (0.45–0.80) — показывать, не подставлять', () => {
  test('«Свеча зажигания иридиевая» → «Свеча зажигания»: уточнение к той же детали', () => {
    const s = scoreOf('Свеча зажигания иридиевая', 'Свеча зажигания', BRANDS);
    const band = bandOf(s.score);
    expect(band, `оценка ${s.score.toFixed(2)} — полоса ${band}`).toBe('choose');
    expect(s.common).toContain('свеча');
  });

  test('«Колодки тормозные передние» → «Колодки тормоaasзные …»: ОПЕЧАТКА В СПРАВОЧНИКЕ', () => {
    // Эталон тоже бывает грязным: мусор внутри слова. Алгоритм обязан её найти, иначе
    // позицию заведут второй раз.
    const s = scoreOf('Колодки тормозные передние',
      'Колодки тормоaasзные передние  и задние', BRANDS);
    expect(s.score, 'опечатку в справочнике не пережил').toBeGreaterThanOrEqual(MATCH_BANDS.choose);
    expect(s.headMatch, 'главное слово «колодки» не совпало').toBe(true);
  });
});

describe('похожесть · АСИММЕТРИЯ: где лишнее слово', () => {
  test('клиент ОПУСТИЛ уточнение — та же деталь, подставлять можно', () => {
    // «Масло моторное 5W-30» против «Масло моторное 5W-30 (5л)»: уточнение есть в
    // справочнике, а клиент его не написал. Все его слова покрыты — позиция та же.
    const s = scoreOf('Масло моторное 5W-30', 'Масло моторное 5W-30 (5л)', BRANDS);
    expect(s.score, 'опущенное уточнение снизило уверенность зря')
      .toBeGreaterThanOrEqual(MATCH_BANDS.auto);
  });

  test('клиент НАПИСАЛ лишнее — это ДРУГАЯ деталь, подставлять нельзя', () => {
    // «иридиевая» — свойство детали, и в справочнике её нет: значит там более
    // простая свеча. Именно эту пару счётчик сначала оценивал как 0.87.
    const s = scoreOf('Свеча зажигания иридиевая', 'Свеча зажигания', BRANDS);
    expect(s.score, 'подставили бы не ту деталь').toBeLessThan(MATCH_BANDS.auto);
    expect(s.score, 'и всё же позиция похожа — её надо показать')
      .toBeGreaterThanOrEqual(MATCH_BANDS.choose);
  });

  test('разные детали с общим главным словом не подставляются', () => {
    // «Фильтр воздушный» против «Фильтр масляный»: главное слово одно, детали разные.
    const s = scoreOf('Фильтр воздушный', 'Фильтр масляный', BRANDS);
    expect(s.score, 'разные фильтры сочтены одним').toBeLessThan(MATCH_BANDS.auto);
  });
});
describe('похожесть · СЛАБО (< 0.45) — честно сомневаться', () => {
  test('«Катушка зажигания» против «Свечи зажигания» — РАЗНЫЕ ДЕТАЛИ', () => {
    const s = scoreOf('Катушка зажигания', 'Свеча зажигания', BRANDS);
    // Общее только слово «зажигания». По Левенштейну здесь было бы 0.65 — выше худшего
    // настоящего совпадения (0.60), то есть уверенно и неверно.
    expect(s.headMatch, 'главные слова «катушка» и «свеча» сочтены совпавшими').toBe(false);
    expect(s.score, `оценка ${s.score.toFixed(2)} — слишком высокая для разных деталей`)
      .toBeLessThan(MATCH_BANDS.choose);
    expect(s.common).toEqual(['зажигания']);
  });

  test('позиции, которых нет в справочнике, не находят себе пары', () => {
    // 15 из 23 написаний в legacy именно такие. Подставить сюда что-либо — выдумать данные.
    const absent = ['Диск сцепления', 'Корзина сцепления', 'Выжимной подшипник',
      'Сальник коленвала задний', 'Провод высоковольтный', 'Решётка радиатора',
      'Фара левая LED', 'Бампер передний в сборе', 'Пружина передней подвески'];

    for (const w of absent) {
      for (const c of ['Фильтр масляный', 'Свеча зажигания', 'Колодки тормозные передние']) {
        const s = scoreOf(w, c, BRANDS);
        expect(s.score, `«${w}» сочтено похожим на «${c}» — ${s.score.toFixed(2)}`)
          .toBeLessThan(MATCH_BANDS.choose);
      }
    }
  });
});

describe('похожесть · полосы', () => {
  test('границы полос заданы явно и работают', () => {
    expect(MATCH_BANDS.auto).toBe(0.8);
    expect(MATCH_BANDS.choose).toBe(0.45);

    expect(bandOf(1)).toBe('auto');
    expect(bandOf(0.8)).toBe('auto');
    expect(bandOf(0.79)).toBe('choose');
    expect(bandOf(0.45)).toBe('choose');
    expect(bandOf(0.44)).toBe('none');
    expect(bandOf(0)).toBe('none');
  });

  test('полоса и оценка не расходятся', () => {
    for (const score of [1, 0.9, 0.8, 0.6, 0.45, 0.44, 0.2, 0]) {
      const expected = score >= 0.8 ? 'auto' : score >= 0.45 ? 'choose' : 'none';
      expect(bandOf(score), `оценка ${score}`).toBe(expected);
    }
  });
});

describe('похожесть · предложения списком', () => {
  const catalogue = [
    { id: '1', name: 'Фильтр масляный' },
    { id: '2', name: 'Фильтр масляный (аналог BOSCH)' },
    { id: '3', name: 'Фильтр воздушный' },
    { id: '4', name: 'Свеча зажигания' },
    { id: '5', name: 'Колодки тормозные передние' },
  ];

  test('лучшее предложение первое', () => {
    const s = suggest('Фильтр воздушный', catalogue, { brands: BRANDS });
    expect(s[0]!.name).toBe('Фильтр воздушный');
    expect(s[0]!.band).toBe('auto');
  });

  test('БЛИЗНЕЦЫ показаны оба — верный ответ не один', () => {
    // «Фильтр масляный» и «Фильтр масляный (аналог BOSCH)» — обе позиции подходят, и
    // выбрать молча одну значило бы решить за оператора.
    const s = suggest('Фильтр масляный', catalogue, { brands: BRANDS });
    const names = s.map((x) => x.name);
    expect(names, 'первый близнец потерян').toContain('Фильтр масляный');
    expect(names, 'второй близнец потерян').toContain('Фильтр масляный (аналог BOSCH)');
    expect(names.length, 'на первое место попало что-то постороннее').toBeGreaterThanOrEqual(2);
  });

  test('объяснение рядом с оценкой: какие слова совпали', () => {
    // Оценка без объяснения оператору не помогает: он не понимает, ПОЧЕМУ предложено.
    const s = suggest('Свеча зажигания иридиевая', catalogue, { brands: BRANDS });
    const top = s[0]!;
    expect(top.name).toBe('Свеча зажигания');
    expect(top.common, 'не показано, какие слова совпали').toContain('свеча');
    expect(top.headMatch).toBe(true);
  });

  test('нулевые совпадения не засоряют список', () => {
    const s = suggest('Диск сцепления', catalogue, { brands: BRANDS });
    expect(s.length, 'показаны предложения с нулевой оценкой').toBe(0);
  });

  test('список ограничен по длине', () => {
    const many = Array.from({ length: 40 }, (_, i) => ({ id: String(i), name: `Фильтр масляный ${i}` }));
    expect(suggest('Фильтр масляный', many, { brands: BRANDS, limit: 3 }).length).toBe(3);
  });

  test('без брендов тоже работает — параметр необязательный', () => {
    const s = suggest('Фильтр масляный', catalogue);
    expect(s[0]!.name).toBe('Фильтр масляный');
  });
});

describe('похожесть · устойчивость', () => {
  test('пустое написание не даёт совпадений', () => {
    expect(suggest('', [{ id: '1', name: 'Фильтр масляный' }]).length).toBe(0);
    expect(scoreOf('', 'Фильтр масляный').score).toBe(0);
  });

  test('пустой справочник не роняет поиск', () => {
    expect(suggest('Фильтр масляный', []).length).toBe(0);
  });

  test('оценка всегда в пределах от 0 до 1', () => {
    const pairs = [['Фильтр', 'Фильтр'], ['а', 'б'], ['Фильтр масляный', 'масло моторное']];
    for (const [a, b] of pairs) {
      const s = scoreOf(a!, b!, BRANDS).score;
      expect(s).toBeGreaterThanOrEqual(0);
      expect(s).toBeLessThanOrEqual(1);
    }
  });

  test('оценка симметрична: порядок аргументов не меняет результат', () => {
    // Иначе сортировка «кого с кем сравниваем» влияла бы на подстановку.
    const a = scoreOf('Фильтр масляный', 'Фильтр воздушный', BRANDS).score;
    const b = scoreOf('Фильтр воздушный', 'Фильтр масляный', BRANDS).score;
    expect(a).toBeCloseTo(b, 10);
  });
});
