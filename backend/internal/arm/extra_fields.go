package arm

// Дополнительные реквизиты строки сверх регистра 1С (ФТ v2 п. 13 «Комментарий и доп. признак»).
// Поле регистра «ДопПризнак» — признак-флажок (бывшая колонка AD файла-реестра); в 1С такое
// настраивается дополнительным реквизитом. fields_gen.go сгенерирован из регистра и править
// его нельзя, поэтому расширение карты полей живёт отдельным init.
func init() {
	Fields["ДопПризнак"] = Field{Column: "extra_flag", Kind: "bool"}
}

// ExtraFieldNames — дополнительные реквизиты строки, которых нет в регистре 1С
// (используются тестами и выгрузкой настроек).
var ExtraFieldNames = []string{"ДопПризнак"}
