package arm

import (
	"math"
	"testing"
)

// TestRound2_GoldenArm — золотые значения округления на write-стороне (arm).
// Точно такая же таблица проверяется в domain (TestRound2_Golden): формулы
// «сумма = количество × цена» на write- и read-стороне обязаны совпадать до копейки.
//
// Обе таблицы намеренно дублируют ожидания литералами: изменение любого round2
// ломает тест в своём пакете, поэтому расхождение двух реализаций не пройдёт незамеченным.
// В Step 11 остаётся одна реализация (domain/money.go), и этот тест удаляется.
func TestRound2_GoldenArm(t *testing.T) {
	cases := []struct{ in, want float64 }{
		{0, 0}, {1, 1}, {1.004, 1.0}, {1.005, 1.01}, {1.006, 1.01},
		{2.675, 2.68}, {1000 * 1.3, 1300}, {-1.005, -1.01}, {-2.675, -2.68},
		{0.1 + 0.2, 0.3}, {999.999, 1000}, {1234.5678, 1234.57},
	}
	for _, c := range cases {
		if got := round2(c.in); math.Abs(got-c.want) > 1e-9 {
			t.Errorf("arm round2(%v) = %v, want %v", c.in, got, c.want)
		}
	}
}
