// Расширение seed для сквозных тестов АРМ: поставщики с договорами, покупатель, номенклатура с разными видами НДС,
// остатки на складе (проведённая приходная накладная). Идемпотентно: объекты ищутся по наименованию с префиксом «E2E ».
//   cscript //E:JScript seed-e2e.js <строка соединения, файл UTF-16> <отчёт, UTF-16>
// Запускать через seed-e2e.ps1 (он перекодирует скрипт в UTF-16 и не даёт запустить на рабочей базе).
var fso = new ActiveXObject('Scripting.FileSystemObject');
var A = WScript.Arguments;
var f = fso.OpenTextFile(A(0), 1, false, -1), cs = f.ReadAll(); f.Close();
var OUT = fso.CreateTextFile(A(1), true, true);
var errors = 0;
function log(s) { OUT.WriteLine(s); }
function step(name, fn) {
  try { var r = fn(); log('OK    ' + name + (r ? ': ' + r : '')); return true; }
  catch (e) { errors++; log('ERROR ' + name + ': ' + String(e.message).replace(/\s+/g, ' ')); return false; }
}

var SUPPLIERS = ['E2E Поставщик Альфа', 'E2E Поставщик Бета'];
var CUSTOMER = 'E2E Покупатель';
// [наименование, вид ставки НДС (Перечисление.ВидыСтавокНДС), закупочная цена, остаток на складе]
var NOMS = [['E2E Колодки тормозные (НДС общая)', 'Общая', 1200, 10],
            ['E2E Фильтр масляный (без НДС)', 'БезНДС', 450, 10],
            ['E2E Книга по ТО (НДС 10%)', 'Пониженная', 300, 10]];
var RECEIPT_COMMENT = 'E2E seed: начальные остатки';

try {
  var c = new ActiveXObject('V83.COMConnector').Connect(cs);
  var q = function (text, params) {
    var z = c.NewObject('Запрос'); z.Текст = text;
    if (params) for (var k in params) z.УстановитьПараметр(k, params[k]);
    return z.Выполнить().Выгрузить();
  };
  var first = function (text, params) { var t = q(text, params); return t.Количество() ? t.Получить(0).Получить(0) : null; };
  var byName = function (catalog, name) { var r = c.Справочники[catalog].НайтиПоНаименованию(name, true); return r.Пустая() ? null : r; };

  var ORG = first('ВЫБРАТЬ ПЕРВЫЕ 1 О.Ссылка ИЗ Справочник.Организации КАК О ГДЕ НЕ О.ПометкаУдаления');
  var WAREHOUSE = first('ВЫБРАТЬ ПЕРВЫЕ 1 С.Ссылка ИЗ Справочник.СтруктурныеЕдиницы КАК С ' +
    'ГДЕ С.ТипСтруктурнойЕдиницы = ЗНАЧЕНИЕ(Перечисление.ТипыСтруктурныхЕдиниц.Склад) И НЕ С.ПометкаУдаления');
  // образцы для копирования: у них заполнены обязательные реквизиты (группа доступа, счета учёта, категория)
  var SAMPLE_CP = first('ВЫБРАТЬ ПЕРВЫЕ 1 К.Ссылка ИЗ Справочник.Контрагенты КАК К ' +
    'ГДЕ НЕ К.ЭтоГруппа И НЕ К.ПометкаУдаления И НЕ К.Наименование ПОДОБНО "E2E%" И НЕ К.Наименование ПОДОБНО "%ФНС%" ' +
    'И К.Ссылка В (ВЫБРАТЬ Д.Владелец ИЗ Справочник.ДоговорыКонтрагентов КАК Д) ' +
    // образец с заполненными счетами расчётов: без них проведение падает «Не заполнен счет кредита» (Журнал проводок)
    'УПОРЯДОЧИТЬ ПО ВЫБОР КОГДА К.СчетУчетаРасчетовСПоставщиком <> ЗНАЧЕНИЕ(ПланСчетов.Управленческий.ПустаяСсылка) ' +
    'И К.СчетУчетаРасчетовСПокупателем <> ЗНАЧЕНИЕ(ПланСчетов.Управленческий.ПустаяСсылка) ТОГДА 0 ИНАЧЕ 1 КОНЕЦ, ' +
    'ВЫБОР КОГДА К.Поставщик ТОГДА 0 ИНАЧЕ 1 КОНЕЦ, К.Код');
  var SAMPLE_CONTRACT = first('ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Справочник.ДоговорыКонтрагентов КАК Д ' +
    'ГДЕ Д.Владелец = &К И НЕ Д.ПометкаУдаления', { 'К': SAMPLE_CP });
  var SAMPLE_NOM = first('ВЫБРАТЬ ПЕРВЫЕ 1 Н.Ссылка ИЗ Справочник.Номенклатура КАК Н ' +
    'ГДЕ НЕ Н.ЭтоГруппа И НЕ Н.ПометкаУдаления И Н.ТипНоменклатуры = ЗНАЧЕНИЕ(Перечисление.ТипыНоменклатуры.Запас) ' +
    'И НЕ Н.Наименование ПОДОБНО "E2E%" УПОРЯДОЧИТЬ ПО Н.Код');
  var UNIT_PCS = first('ВЫБРАТЬ ПЕРВЫЕ 1 Е.Ссылка ИЗ Справочник.КлассификаторЕдиницИзмерения КАК Е ' +
    'ГДЕ Е.Наименование = "шт" И НЕ Е.ПометкаУдаления');
  log('База: организация ' + c.String(ORG) + ', склад ' + c.String(WAREHOUSE) + '; образцы: контрагент ' + c.String(SAMPLE_CP) +
      ', договор ' + c.String(SAMPLE_CONTRACT) + ', номенклатура ' + c.String(SAMPLE_NOM) + ', единица «шт» ' + (UNIT_PCS ? 'есть' : 'нет'));

  // ---------------------------------------------------------------- контрагенты и договоры
  var counterparty = function (name, isSupplier) {
    var ref = byName('Контрагенты', name), created = !ref;
    var o = ref ? ref.ПолучитьОбъект() : SAMPLE_CP.Скопировать();
    o.Наименование = name; o.НаименованиеПолное = name;
    o.Покупатель = !isSupplier; o.Поставщик = !!isSupplier;
    o.ИНН = ''; o.КПП = '';
    // счета расчётов по умолчанию, если у образца пустые (иначе проведение: «Не заполнен счет кредита»)
    var acc = { СчетУчетаРасчетовСПоставщиком: 'РасчетыСПоставщиками', СчетУчетаАвансовПоставщику: 'АвансыВыданные',
                СчетУчетаРасчетовСПокупателем: 'РасчетыСПокупателями', СчетУчетаАвансовПокупателя: 'АвансыПолученные' };
    for (var a in acc) {
      try { if (o[a].Пустая()) o[a] = c.ПланыСчетов.Управленческий[acc[a]]; } catch (e) { log('WARN  счёт ' + a + ': ' + e.message); }
    }
    o.Записать();
    ref = o.Ссылка;
    var kind = isSupplier ? 'СПоставщиком' : 'СПокупателем';
    var cn = first('ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Справочник.ДоговорыКонтрагентов КАК Д ГДЕ Д.Владелец = &К И НЕ Д.ПометкаУдаления', { 'К': ref });
    var d = cn ? cn.ПолучитьОбъект() : SAMPLE_CONTRACT.Скопировать();
    d.Владелец = ref; d.Организация = ORG;
    d.Наименование = isSupplier ? 'Договор поставки E2E' : 'Договор с покупателем E2E';
    d.НомерДоговора = isSupplier ? 'E2E-П' : 'E2E-К';
    d.ВидДоговора = c.Перечисления.ВидыДоговоров[kind];
    d.Записать();
    return (created ? 'создан' : 'обновлён') + ', договор «' + d.Наименование + '» (' + kind + ')';
  };
  for (var i = 0; i < SUPPLIERS.length; i++) (function (n) { step('поставщик ' + n, function () { return counterparty(n, true); }); })(SUPPLIERS[i]);
  step('покупатель ' + CUSTOMER, function () { return counterparty(CUSTOMER, false); });

  // ---------------------------------------------------------------- номенклатура с видами НДС
  for (var i = 0; i < NOMS.length; i++) (function (n) {
    step('номенклатура ' + n[0], function () {
      var ref = byName('Номенклатура', n[0]), created = !ref;
      // уже создана (в т.ч. seed-nomenclature-odata.mjs, где запись через COM не проходит) и вид ставки верный — не переписываем
      if (ref && c.String(ref.ВидСтавкиНДС) == c.String(c.Перечисления.ВидыСтавокНДС[n[1]])) return 'есть, ВидСтавкиНДС=' + c.String(ref.ВидСтавкиНДС);
      var o = ref ? ref.ПолучитьОбъект() : SAMPLE_NOM.Скопировать();
      o.Наименование = n[0]; o.НаименованиеПолное = n[0];
      o.Артикул = 'E2E-' + (i + 1);
      o.ТипНоменклатуры = c.Перечисления.ТипыНоменклатуры.Запас;
      o.ВидСтавкиНДС = c.Перечисления.ВидыСтавокНДС[n[1]];
      if (UNIT_PCS) o.ЕдиницаИзмерения = UNIT_PCS;
      o.Поставщик = byName('Контрагенты', SUPPLIERS[0]) || o.Поставщик;
      o.Записать();
      return (created ? 'создана' : 'обновлена') + ', ВидСтавкиНДС=' + c.String(o.ВидСтавкиНДС);
    });
  })(NOMS[i]);

  // ---------------------------------------------------------------- остатки: приходная накладная от поставщика Альфа
  step('остатки (приходная накладная)', function () {
    var supplier = byName('Контрагенты', SUPPLIERS[0]);
    var contract = first('ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка ИЗ Справочник.ДоговорыКонтрагентов КАК Д ГДЕ Д.Владелец = &К И НЕ Д.ПометкаУдаления', { 'К': supplier });
    var ex = first('ВЫБРАТЬ ПЕРВЫЕ 1 П.Ссылка ИЗ Документ.ПриходнаяНакладная КАК П ГДЕ П.Комментарий ПОДОБНО &К И НЕ П.ПометкаУдаления', { 'К': RECEIPT_COMMENT });
    var d = ex ? ex.ПолучитьОбъект() : c.Документы.ПриходнаяНакладная.СоздатьДокумент();
    if (!ex) { d.Дата = new Date().getVarDate(); d.Заполнить(c.Неопределено); }
    d.ВидОперации = c.Перечисления.ВидыОперацийПриходнаяНакладная.ПоступлениеОтПоставщика;
    d.Организация = ORG; d.Контрагент = supplier; d.Договор = contract;
    d.СтруктурнаяЕдиница = WAREHOUSE; d.Комментарий = RECEIPT_COMMENT;
    if (!d.ВалютаДокумента || d.ВалютаДокумента.Пустая()) d.ВалютаДокумента = c.Константы.НациональнаяВалюта.Получить();
    if (!d.Курс) { d.Курс = 1; d.Кратность = 1; }
    if (!d.НалогообложениеНДС || d.НалогообложениеНДС.Пустая()) d.НалогообложениеНДС = c.Перечисления.ТипыНалогообложенияНДС.НеОблагаетсяНДС;
    d.СуммаВключаетНДС = true;
    d.Запасы.Очистить();
    var total = 0;
    for (var i = 0; i < NOMS.length; i++) {
      var nom = byName('Номенклатура', NOMS[i][0]);
      var r = d.Запасы.Добавить();
      r.Номенклатура = nom; r.ЕдиницаИзмерения = nom.ЕдиницаИзмерения;
      r.Количество = NOMS[i][3]; r.Цена = NOMS[i][2]; r.Сумма = NOMS[i][2] * NOMS[i][3];
      r.СтавкаНДС = c.Справочники.СтавкиНДС.СтавкаНДС(c.Перечисления.ВидыСтавокНДС.БезНДС, d.Дата);
      r.СуммаНДС = 0; r.Всего = r.Сумма; total += r.Сумма;
    }
    d.СуммаДокумента = total;
    d.Записать(c.РежимЗаписиДокумента.Проведение);
    return (ex ? 'перепроведена' : 'создана') + ' № ' + d.Номер + ' от ' + c.String(d.Дата) + ', сумма ' + total;
  });

  // ---------------------------------------------------------------- проверка
  var t = q('ВЫБРАТЬ О.Номенклатура.Наименование КАК Н, СУММА(О.КоличествоОстаток) КАК К ' +
    'ИЗ РегистрНакопления.ЗапасыНаСкладах.Остатки(, Номенклатура.Наименование ПОДОБНО "E2E%") КАК О СГРУППИРОВАТЬ ПО О.Номенклатура.Наименование');
  for (var i = 0; i < t.Количество(); i++) log('остаток  ' + t.Получить(i).Н + ' = ' + t.Получить(i).К);
  if (t.Количество() < NOMS.length) { errors++; log('ERROR остатки: позиций с остатком ' + t.Количество() + ' из ' + NOMS.length); }
} catch (e) { errors++; log('ERROR ' + String(e.message).replace(/\s+/g, ' ')); }
log(errors ? 'ИТОГ: ошибок ' + errors : 'ИТОГ: OK');
OUT.Close();
